function formatDuration(totalSeconds) {
    const seconds = Number(totalSeconds) || 0;

    if (seconds <= 0) return "None";
    if (seconds < 60) return `${seconds} sec`;

    const minutes = Math.floor(seconds / 60);
    const remainingSeconds = seconds % 60;

    if (minutes < 60) {
        return remainingSeconds
            ? `${minutes} min ${remainingSeconds} sec`
            : `${minutes} min`;
    }

    const hours = Math.floor(minutes / 60);
    const remainingMinutes = minutes % 60;

    return remainingMinutes
        ? `${hours} hr ${remainingMinutes} min`
        : `${hours} hr`;
}

function targetText(plan) {
    return plan.targetSeconds === 0
        ? "No planned absence"
        : `Target absence: ${formatDuration(plan.targetSeconds)}`;
}

function getLocalDateText(date = new Date()) {
    const year = date.getFullYear();
    const month = String(date.getMonth() + 1).padStart(2, "0");
    const day = String(date.getDate()).padStart(2, "0");

    return `${year}-${month}-${day}`;
}

function formatDate(dateText) {
    return new Date(`${dateText}T00:00:00`).toLocaleDateString("en-ZA", {
        day: "2-digit",
        month: "short",
        year: "numeric"
    });
}

function escapeHtml(value) {
    return String(value)
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;")
        .replaceAll('"', "&quot;")
        .replaceAll("'", "&#039;");
}

function sortSessions(sessionList) {
    return [...sessionList].sort(function (firstSession, secondSession) {
        const dateDifference =
            new Date(`${firstSession.date}T00:00:00`) -
            new Date(`${secondSession.date}T00:00:00`);

        if (dateDifference !== 0) return dateDifference;

        const firstCreated = new Date(
            firstSession.createdAt || `${firstSession.date}T00:00:00`
        ).getTime();
        const secondCreated = new Date(
            secondSession.createdAt || `${secondSession.date}T00:00:00`
        ).getTime();

        if (firstCreated !== secondCreated) return firstCreated - secondCreated;

        return String(firstSession.id).localeCompare(String(secondSession.id));
    });
}

function getSessionsForDate(dateText) {
    return sortSessions(
        sessions.filter(function (session) {
            return session.date === dateText;
        })
    );
}

function normaliseDailySessionNumbers() {
    const ordered = sortSessions(sessions);
    const counts = {};

    ordered.forEach(function (session) {
        counts[session.date] = (counts[session.date] || 0) + 1;
        session.dailySession = counts[session.date];
    });

    sessions = ordered;
}

