function updateLegacyImportBanner() {
    const legacySessions = readLegacySessions();
    const importMarker = currentUser
        ? localStorage.getItem(`miloSupabaseImported_${currentUser.id}`)
        : null;

    legacyImportBanner.hidden = !(
        currentUser &&
        sessions.length === 0 &&
        legacySessions.length > 0 &&
        !importMarker
    );
}

async function importLegacySessions() {
    const legacySessions = readLegacySessions();

    if (!legacySessions.length) {
        window.alert("No old browser sessions were found.");
        updateLegacyImportBanner();
        return;
    }

    if (sessions.length > 0) {
        window.alert(
            "Supabase already contains sessions. The automatic importer only runs on an empty cloud tracker to prevent duplicates."
        );
        return;
    }

    if (!window.confirm(
        `Import ${legacySessions.length} old session${legacySessions.length === 1 ? "" : "s"} into Supabase?`
    )) {
        return;
    }

    setLoading(true, "Importing old sessions into Supabase…");

    try {
        const rows = sortLegacySessions(legacySessions).map(function (session, index) {
            return {
                user_id: currentUser.id,
                ...migrateLegacySession(session, index)
            };
        });

        const { error } = await supabaseClient
            .from("milo_training_sessions")
            .insert(rows);

        if (error) throw error;

        // The imported session history determines the recommendation.
        // An old saved setting is deliberately ignored.
        localStorage.setItem(`miloSupabaseImported_${currentUser.id}`, "yes");
        await loadTrackerData({
            quiet: true,
            reason: "Your old browser sessions were imported into Supabase."
        });

        window.alert("Your old sessions are now saved in Supabase.");
    } catch (error) {
        console.error(error);
        window.alert(`The old sessions could not be imported: ${error.message}`);
    } finally {
        setLoading(false);
    }
}

function sortLegacySessions(sessionList) {
    return [...sessionList].sort(function (firstSession, secondSession) {
        const dateDifference =
            new Date(`${firstSession.date}T00:00:00`) -
            new Date(`${secondSession.date}T00:00:00`);

        if (dateDifference !== 0) return dateDifference;
        return Number(firstSession.id || 0) - Number(secondSession.id || 0);
    });
}

