// ---------- TRAINING PLAN HELPERS ----------

function getPlan(duration, level) {
    return trainingPlans.find(function (plan) {
        return (
            plan.duration === Number(duration) &&
            plan.level === Number(level)
        );
    }) || trainingPlans[0];
}

function getPlanIndex(duration, level) {
    return trainingPlans.findIndex(function (plan) {
        return (
            plan.duration === Number(duration) &&
            plan.level === Number(level)
        );
    });
}

function getPlanName(plan) {
    return `${plan.duration}-minute Level ${plan.level}`;
}

function getHardestCompletedPlan() {
    if (sessions.length === 0) {
        return null;
    }

    let hardestIndex = 0;

    sessions.forEach(function (session) {
        const planIndex = getPlanIndex(session.duration, session.level);

        if (planIndex > hardestIndex) {
            hardestIndex = planIndex;
        }
    });

    return trainingPlans[hardestIndex];
}


// ---------- AUTOMATIC RECOMMENDATION LOGIC ----------

function calculateRecommendation(sessionList) {
    const orderedSessions = sortSessionsChronologically(sessionList);

    if (orderedSessions.length === 0) {
        return {
            plan: trainingPlans[0],
            action: "start",
            reason:
                "Milo has no saved results yet, so begin with the easiest 10-minute session."
        };
    }

    const lastSession = orderedSessions[orderedSessions.length - 1];
    const currentPlanIndex = Math.max(
        getPlanIndex(lastSession.duration, lastSession.level),
        0
    );

    if (orderedSessions.length < 2) {
        return {
            plan: trainingPlans[currentPlanIndex],
            action: "repeat",
            reason:
                "Only one result is available. Repeat the same session until two consecutive scores can be compared."
        };
    }

    const previousSession = orderedSessions[orderedSessions.length - 2];

    const sameSession =
        Number(previousSession.duration) === Number(lastSession.duration) &&
        Number(previousSession.level) === Number(lastSession.level);

    if (!sameSession) {
        return {
            plan: trainingPlans[currentPlanIndex],
            action: "repeat",
            reason:
                "The two latest results used different sessions, so repeat the most recent session to build a clear score pattern."
        };
    }

    const twoHighScores =
        Number(previousSession.calmness) >= 4 &&
        Number(lastSession.calmness) >= 4;

    if (twoHighScores) {
        const nextPlanIndex = Math.min(
            currentPlanIndex + 1,
            trainingPlans.length - 1
        );

        if (nextPlanIndex === currentPlanIndex) {
            return {
                plan: trainingPlans[currentPlanIndex],
                action: "highest",
                reason:
                    "Milo scored 4 or 5 twice in a row and has reached the hardest session in this tracker."
            };
        }

        return {
            plan: trainingPlans[nextPlanIndex],
            action: "move-up",
            reason:
                "Milo scored 4 or 5 twice in a row on the same session, so the next harder session is recommended."
        };
    }

    const twoLowScores =
        Number(previousSession.calmness) <= 2 &&
        Number(lastSession.calmness) <= 2;

    if (twoLowScores) {
        const easierPlanIndex = Math.max(currentPlanIndex - 1, 0);

        if (easierPlanIndex === currentPlanIndex) {
            return {
                plan: trainingPlans[currentPlanIndex],
                action: "easiest",
                reason:
                    "Milo scored 1 or 2 twice in a row, but he is already on the easiest session. Repeat it gently."
            };
        }

        return {
            plan: trainingPlans[easierPlanIndex],
            action: "move-down",
            reason:
                "Milo scored 1 or 2 twice in a row on the same session, so an easier session is recommended."
        };
    }

    return {
        plan: trainingPlans[currentPlanIndex],
        action: "repeat",
        reason:
            "The latest two scores do not yet form two high or two low scores, so repeat the current session."
    };
}


// ---------- FORMAT AND SAFETY HELPERS ----------

function formatDate(dateText) {
    const date = new Date(`${dateText}T00:00:00`);

    return date.toLocaleDateString("en-ZA", {
        day: "2-digit",
        month: "short",
        year: "numeric"
    });
}

function escapeHtml(value) {
    return String(value)
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;")
        .replaceAll('"', "&quot;")
        .replaceAll("'", "&#039;");
}


