exportButton.addEventListener("click", function () {
    if (!sessions.length) {
        window.alert("There are no sessions to export yet.");
        return;
    }

    const headings = [
        "Date",
        "Daily session",
        "Plan ID",
        "Stage",
        "Plan title",
        "Target absence",
        "Calmness",
        "Crying",
        "Actual absence seconds",
        "Notes"
    ];

    const rows = sortSessions(sessions).map(function (session) {
        const plan = getPlan(session.planId);
        return [
            session.date,
            session.dailySession,
            plan.id,
            plan.stageLabel,
            plan.title,
            plan.targetSeconds,
            session.calmness,
            session.crying,
            session.absenceSecondsTotal,
            session.notes
        ];
    });

    const csv = [headings, ...rows]
        .map(function (row) {
            return row
                .map(function (value) {
                    return `"${String(value).replaceAll('"', '""')}"`;
                })
                .join(",");
        })
        .join("\n");

    const url = URL.createObjectURL(
        new Blob([csv], { type: "text/csv" })
    );
    const link = document.createElement("a");
    link.href = url;
    link.download = "milo-supabase-pen-training-progress.csv";
    document.body.appendChild(link);
    link.click();
    link.remove();
    URL.revokeObjectURL(url);
});

