async function initialiseSupabaseApp() {
    renderPlanList("all");
    renderPlanDetail("F01");
    sessionDate.value = getLocalDateText();

    if (!isSupabaseConfigured()) {
        showAuthMessage(
            "Supabase is not configured yet. Open supabase-config.js and paste your Project URL and publishable key.",
            true
        );
        return;
    }

    if (!window.supabase?.createClient) {
        showAuthMessage(
            "The Supabase library did not load. Check your internet connection and refresh the page.",
            true
        );
        return;
    }

    supabaseClient = window.supabase.createClient(
        cleanedSupabaseUrl,
        config.supabasePublishableKey,
        {
            auth: {
                persistSession: true,
                autoRefreshToken: true,
                detectSessionInUrl: true
            }
        }
    );

    supabaseClient.auth.onAuthStateChange(function (event, session) {
        window.setTimeout(function () {
            if (event === "SIGNED_IN" && session?.user) {
                if (!currentUser || currentUser.id !== session.user.id) {
                    enterSignedInApp(session.user);
                }
            }

            if (event === "SIGNED_OUT") {
                showSignedOutScreen();
            }
        }, 0);
    });

    const { data, error } = await supabaseClient.auth.getSession();

    if (error) {
        showAuthMessage(`Could not check your login: ${error.message}`, true);
        return;
    }

    if (data.session?.user) {
        await enterSignedInApp(data.session.user);
    } else {
        showSignedOutScreen();
    }
}

initialiseSupabaseApp();
