function filterMatches(plan, filter) {
    if (filter === "all") return true;
    if (filter === "foundation") return plan.category === "foundation";
    if (filter === "short") {
        return plan.targetSeconds >= 30 && plan.targetSeconds <= 300;
    }
    if (filter === "medium") {
        return plan.targetSeconds >= 480 && plan.targetSeconds <= 1200;
    }
    if (filter === "long") return plan.targetSeconds >= 1800;
    return true;
}

