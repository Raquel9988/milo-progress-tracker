async function loadTrackerData(options = {}) {
    if (!currentUser || isLoadingData) return;

    const quiet = Boolean(options.quiet);
    isLoadingData = true;

    if (!quiet) setLoading(true, "Syncing Milo's sessions…");
    setSyncStatus("Syncing…", "syncing");

    try {
        const [sessionsResult, settingsResult] = await Promise.all([
            supabaseClient
                .from("milo_training_sessions")
                .select(
                    "id, session_date, plan_id, calmness, crying, absence_seconds, notes, created_at"
                )
                .order("session_date", { ascending: true })
                .order("created_at", { ascending: true }),
            supabaseClient
                .from("milo_tracker_settings")
                .select("current_plan_id")
                .maybeSingle()
        ]);

        if (sessionsResult.error) throw sessionsResult.error;
        if (settingsResult.error) throw settingsResult.error;

        sessions = (sessionsResult.data || []).map(databaseRowToSession);
        normaliseDailySessionNumbers();

        // Recalculate from the actual session history every time data loads.
        // A stale value in milo_tracker_settings can never send Milo back to
        // Foundation 1 when the latest trained plan was higher.
        const recommendation = applyHistoryRecommendation();
        await saveCurrentPlanSetting();

        displaySessions();
        updateSummary();
        updateRecommendations({
            ...recommendation,
            reason: options.reason
                ? `${options.reason} ${recommendation.reason}`
                : recommendation.reason
        });
        prepareRecommendedFormValues();
        updateLegacyImportBanner();

        setSyncStatus(`Synced ${new Date().toLocaleTimeString([], {
            hour: "2-digit",
            minute: "2-digit"
        })}`);
    } catch (error) {
        console.error(error);
        setSyncStatus("Sync failed", "error");
        window.alert(`Could not sync the tracker: ${error.message}`);
    } finally {
        isLoadingData = false;
        if (!quiet) setLoading(false);
    }
}

