// The recommendation is always anchored to the most recently completed plan.
// This means that a plan chosen manually becomes the new baseline immediately.
function getLatestSession() {
    const ordered = sortSessions(sessions);
    return ordered.length ? ordered[ordered.length - 1] : null;
}

function getLatestTwoSessions() {
    const ordered = sortSessions(sessions);
    return ordered.slice(-2);
}

function calculateRecommendationFromHistory() {
    const latestSession = getLatestSession();

    if (!latestSession) {
        return {
            plan: trainingPlans[0],
            action: "start",
            reason:
                "No sessions are saved yet, so begin with Foundation 1."
        };
    }

    const latestPlan = getPlan(latestSession.planId);
    const latestPlanIndex = getPlanIndex(latestPlan.id);
    const latestTwo = getLatestTwoSessions();

    // A single result—or two results on different plans—does not trigger a
    // level change. The last plan trained remains the recommendation.
    if (
        latestTwo.length < 2 ||
        latestTwo[0].planId !== latestPlan.id ||
        latestTwo[1].planId !== latestPlan.id
    ) {
        return {
            plan: latestPlan,
            action: "repeat-latest",
            reason:
                `Your latest trained plan was ${latestPlan.stageLabel}: ${latestPlan.title}. ` +
                "Repeat this same plan once more before upgrading or downgrading."
        };
    }

    const firstScore = Number(latestTwo[0].calmness);
    const secondScore = Number(latestTwo[1].calmness);
    const twoGood = firstScore >= 4 && secondScore >= 4;
    const twoBad = firstScore <= 2 && secondScore <= 2;

    if (twoGood) {
        if (latestPlanIndex >= trainingPlans.length - 1) {
            return {
                plan: latestPlan,
                action: "highest",
                reason:
                    `Milo scored ${firstScore}/5 and ${secondScore}/5 on ${latestPlan.stageLabel}. ` +
                    "He is already at the highest plan, so maintain this stage."
            };
        }

        const upgradedPlan = trainingPlans[latestPlanIndex + 1];

        return {
            plan: upgradedPlan,
            action: "move-up",
            reason:
                `Milo scored ${firstScore}/5 and ${secondScore}/5 in two consecutive ${latestPlan.stageLabel} sessions. ` +
                `The next recommendation is ${upgradedPlan.stageLabel}: ${upgradedPlan.title}.`
        };
    }

    if (twoBad) {
        if (latestPlanIndex <= 0) {
            return {
                plan: latestPlan,
                action: "easiest",
                reason:
                    `Milo scored ${firstScore}/5 and ${secondScore}/5 on the easiest plan. ` +
                    "Repeat it gently and shorten the difficult parts."
            };
        }

        const easierPlan = trainingPlans[latestPlanIndex - 1];

        return {
            plan: easierPlan,
            action: "move-down",
            reason:
                `Milo scored ${firstScore}/5 and ${secondScore}/5 in two consecutive ${latestPlan.stageLabel} sessions. ` +
                `The next recommendation is the easier ${easierPlan.stageLabel}: ${easierPlan.title}.`
        };
    }

    return {
        plan: latestPlan,
        action: "remain",
        reason:
            `Milo's last two ${latestPlan.stageLabel} scores were ${firstScore}/5 and ${secondScore}/5. ` +
            "Because the results are mixed, the recommendation remains on the same plan."
    };
}

function applyHistoryRecommendation() {
    const recommendation = calculateRecommendationFromHistory();
    currentPlanId = recommendation.plan.id;
    return recommendation;
}

function getConsolidationPlan(currentPlan) {
    if (currentPlan.targetSeconds < 900) return currentPlan;

    const fiveMinutePlan = trainingPlans.find(function (plan) {
        return plan.targetSeconds === 300;
    });

    return (
        fiveMinutePlan ||
        trainingPlans[Math.max(0, getPlanIndex(currentPlan.id) - 1)]
    );
}

function getNextDailyPlan() {
    const currentPlan = getPlan(currentPlanId);
    const today = getSessionsForDate(getLocalDateText());
    const longAttemptDone = today.some(function (session) {
        return (
            session.planId === currentPlan.id &&
            currentPlan.targetSeconds >= 900
        );
    });

    if (longAttemptDone) {
        return {
            plan: getConsolidationPlan(currentPlan),
            consolidation: true
        };
    }

    return { plan: currentPlan, consolidation: false };
}

// ---------- SUMMARY AND RECOMMENDATION CARDS ----------
function updateSummary() {
    totalSessions.textContent = sessions.length;

    totalMinutes.textContent = sessions.reduce(function (total, session) {
        return total + getPlan(session.planId).durationMinutes;
    }, 0);

    if (!sessions.length) {
        averageCalmness.textContent = "0/5";
        longestRecordedAbsence.textContent = "None";
    } else {
        const average =
            sessions.reduce(function (total, session) {
                return total + Number(session.calmness);
            }, 0) / sessions.length;

        averageCalmness.textContent = `${average.toFixed(1)}/5`;
        longestRecordedAbsence.textContent = formatDuration(
            Math.max(
                ...sessions.map(function (session) {
                    return Number(session.absenceSecondsTotal) || 0;
                })
            )
        );
    }

    const currentPlan = getPlan(currentPlanId);
    currentStageSummary.textContent = currentPlan.stageLabel;
}

function fillRecommendationCard(cardNumber, completedSession, nextPlanInfo) {
    const card = document.getElementById(`dailySession${cardNumber}`);
    const badge = card.querySelector(".recommendation-badge");
    const stageLabel = card.querySelector(".recommended-stage-label");
    const name = card.querySelector(".recommended-session-name");
    const target = card.querySelector(".recommended-session-target");
    const focus = card.querySelector(".recommended-session-focus");
    const note = card.querySelector(".recommended-session-note");
    const button = card.querySelector(".card-plan-button");

    card.classList.remove(
        "completed-session",
        "next-session",
        "future-session"
    );

    if (completedSession) {
        const plan = getPlan(completedSession.planId);
        card.classList.add("completed-session");
        badge.textContent = "Completed";
        stageLabel.textContent = plan.stageLabel;
        name.textContent = plan.title;
        target.textContent = `${targetText(plan)} • Score ${completedSession.calmness}/5`;
        focus.textContent = plan.challenge;
        note.textContent = `Saved in Supabase as today's Session ${completedSession.dailySession}.`;
        button.dataset.planId = plan.id;
        return;
    }

    const today = getSessionsForDate(getLocalDateText());
    const nextNumber = Math.min(today.length + 1, 3);
    const plan = nextPlanInfo.plan;

    if (cardNumber === nextNumber) {
        card.classList.add("next-session");
        badge.textContent = nextPlanInfo.consolidation
            ? "Easy consolidation"
            : "Recommended next";
        note.textContent = nextPlanInfo.consolidation
            ? "A full long-stage attempt is already saved today, so use this easier plan."
            : "Use this plan next. It will update after the result is saved.";
    } else {
        card.classList.add("future-session");
        badge.textContent = "Planned for now";
        note.textContent = `This will recalculate after Session ${cardNumber - 1} is saved.`;
    }

    stageLabel.textContent = plan.stageLabel;
    name.textContent = plan.title;
    target.textContent = targetText(plan);
    focus.textContent = plan.challenge;
    button.dataset.planId = plan.id;
}

function updateRecommendations(status = {}) {
    const today = getSessionsForDate(getLocalDateText()).slice(0, 3);
    const nextPlanInfo = getNextDailyPlan();

    todaySessionCount.textContent = `${today.length} of 3 complete`;
    const recommendation = status.reason
        ? status
        : calculateRecommendationFromHistory();

    recommendationReason.textContent = recommendation.reason;

    useRecommendationButton.disabled = today.length >= 3;
    useRecommendationButton.textContent =
        today.length >= 3
            ? "Today's Training Complete"
            : "Use Next Recommendation";

    for (let cardNumber = 1; cardNumber <= 3; cardNumber += 1) {
        fillRecommendationCard(
            cardNumber,
            today[cardNumber - 1],
            nextPlanInfo
        );
    }
}

