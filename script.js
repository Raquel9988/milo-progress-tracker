async function sendMagicLink(event) {
    event.preventDefault();

    if (!supabaseClient) {
        showAuthMessage(
            "Supabase is not configured yet. Complete supabase-config.js first.",
            true
        );
        return;
    }

    const email = loginEmail.value.trim().toLowerCase();

    if (!email) return;

    sendLoginButton.disabled = true;
    sendLoginButton.textContent = "Sending…";
    showAuthMessage("Sending your secure login link…");

    try {
        const { error } = await supabaseClient.auth.signInWithOtp({
            email,
            options: {
                emailRedirectTo: getRedirectUrl(),
                shouldCreateUser: true
            }
        });

        if (error) throw error;

        showAuthMessage(
            "Login link sent. Open the email from Supabase and tap the link. You may close this tab."
        );
    } catch (error) {
        console.error(error);
        showAuthMessage(`Could not send the login link: ${error.message}`, true);
    } finally {
        sendLoginButton.disabled = false;
        sendLoginButton.textContent = "Send Login Link";
    }
}

